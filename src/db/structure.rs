/// Label for the parameter row a base type accepts, if any.
pub fn type_params_label(base: &str) -> Option<&'static str> {
    match base.trim().to_ascii_lowercase().as_str() {
        "varchar" | "char" | "nvarchar" | "nchar" | "varbinary" | "binary"
        | "character varying" | "character" => Some("Length"),
        "numeric" | "decimal" => Some("Precision, scale"),
        _ => None,
    }
}

/// Split `varchar(255)` into (`varchar`, `255`); passthrough when no parens.
pub fn split_type(t: &str) -> (String, String) {
    match t.split_once('(') {
        Some((base, rest)) => (
            base.trim().to_string(),
            rest.trim_end().trim_end_matches(')').trim().to_string(),
        ),
        None => (t.trim().to_string(), String::new()),
    }
}

/// Recompose a base type and optional parameter list into one type name.
pub fn join_type(base: &str, params: &str) -> String {
    let base = base.trim();
    let params = params.trim();
    if params.is_empty() {
        base.to_string()
    } else {
        format!("{base}({params})")
    }
}

/// Dialect-default identity used by the column form's auto-increment toggle.
pub fn default_identity(kind: DbKind) -> IdentityKind {
    match kind {
        DbKind::Postgres => IdentityKind::ByDefault,
        DbKind::MySql | DbKind::Sqlite => IdentityKind::AutoIncrement,
        DbKind::MsSql => IdentityKind::MsIdentity,
    }
}

