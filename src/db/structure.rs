//! Structured table introspection, the editable "working model" behind the
//! Structure view, and per-dialect ALTER/CREATE generation.
//!
//! Flow: `Driver::describe_structure` returns a [`TableStructure`] snapshot →
//! the UI converts it into a [`WorkingTable`] (stable ids + origin snapshots)
//! → edits mutate the working model → [`generate`] diffs working vs origin and
//! emits ordered, dialect-correct DDL statements.

use super::DbKind;

/// Stable identity for an object inside one `WorkingTable`. Lets keys,
/// indexes and FKs keep referencing a column across renames.
pub type ObjId = u64;

// ---------------------------------------------------------------------------
// Introspected snapshot
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum IdentityKind {
    #[default]
    None,
    /// Postgres `GENERATED ALWAYS AS IDENTITY`
    Always,
    /// Postgres `GENERATED BY DEFAULT AS IDENTITY`
    ByDefault,
    /// MySQL `AUTO_INCREMENT`
    AutoIncrement,
    /// SQL Server `IDENTITY(1,1)`
    MsIdentity,
}

impl IdentityKind {
    pub fn label(self) -> &'static str {
        match self {
            IdentityKind::None => "none",
            IdentityKind::Always => "identity (always)",
            IdentityKind::ByDefault => "identity (by default)",
            IdentityKind::AutoIncrement => "AUTO_INCREMENT",
            IdentityKind::MsIdentity => "IDENTITY(1,1)",
        }
    }

    /// Choices offered when creating a NEW column on the given dialect.
    pub fn options(kind: DbKind) -> &'static [IdentityKind] {
        match kind {
            DbKind::Postgres => &[IdentityKind::None, IdentityKind::ByDefault, IdentityKind::Always],
            DbKind::MySql => &[IdentityKind::None, IdentityKind::AutoIncrement],
            DbKind::MsSql => &[IdentityKind::None, IdentityKind::MsIdentity],
            DbKind::Sqlite => &[IdentityKind::None, IdentityKind::AutoIncrement],
        }
    }
}

#[derive(Debug, Clone)]
pub struct ColumnInfo {
    pub name: String,
    pub type_name: String,
    pub not_null: bool,
    pub default: Option<String>,
    pub identity: IdentityKind,
    /// Generated/computed column — shown read-only, never altered.
    pub generated: bool,
    /// SQL Server: name of the default constraint backing `default`.
    pub default_constraint: Option<String>,
}

#[derive(Debug, Clone)]
pub struct KeyInfo {
    pub name: Option<String>,
    pub columns: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct FkInfo {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    pub on_delete: String,
    pub on_update: String,
}

#[derive(Debug, Clone)]
pub struct IndexInfo {
    pub name: String,
    pub columns: Vec<String>,
    pub unique: bool,
}

#[derive(Debug, Clone)]
pub struct CheckInfo {
    pub name: String,
    pub expression: String,
}

#[derive(Debug, Clone, Default)]
pub struct TableStructure {
    pub schema: String,
    pub name: String,
    pub columns: Vec<ColumnInfo>,
    pub primary_key: Option<KeyInfo>,
    pub foreign_keys: Vec<FkInfo>,
    /// Secondary indexes only (no PK / constraint-backed indexes).
    pub indexes: Vec<IndexInfo>,
    pub checks: Vec<CheckInfo>,
}

/// Result of executing a DDL batch. Not a `Result` because a partial MySQL
/// apply is not simply an error — the caller needs the applied count.
#[derive(Debug, Clone)]
pub struct DdlOutcome {
    pub applied: usize,
    pub error: Option<String>,
}

// ---------------------------------------------------------------------------
// Working model (editable, diffable)
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ChangeState {
    Unchanged,
    Added,
    Modified,
    Dropped,
}

#[derive(Debug, Clone)]
pub struct WorkingColumn {
    pub id: ObjId,
    pub name: String,
    pub type_name: String,
    pub not_null: bool,
    /// Empty string = no default.
    pub default: String,
    pub identity: IdentityKind,
    pub generated: bool,
    pub origin: Option<ColumnInfo>,
    pub dropped: bool,
}

impl WorkingColumn {
    pub fn state(&self) -> ChangeState {
        if self.dropped {
            return ChangeState::Dropped;
        }
        match &self.origin {
            None => ChangeState::Added,
            Some(o) => {
                if self.name != o.name
                    || self.type_name != o.type_name
                    || self.not_null != o.not_null
                    || norm(&self.default) != norm_opt(&o.default)
                {
                    ChangeState::Modified
                } else {
                    ChangeState::Unchanged
                }
            }
        }
    }
}

#[derive(Debug, Clone, Default)]
pub struct PkState {
    pub present: bool,
    /// Empty = let the DB pick / dialect default. Ignored on MySQL.
    pub name: String,
    pub column_ids: Vec<ObjId>,
    pub origin: Option<KeyInfo>,
    /// Ids the origin columns mapped to at load time, for rename-proof diffs.
    pub origin_ids: Vec<ObjId>,
}

impl PkState {
    pub fn state(&self) -> ChangeState {
        match (&self.origin, self.present) {
            (None, false) => ChangeState::Unchanged,
            (None, true) => ChangeState::Added,
            (Some(_), false) => ChangeState::Dropped,
            (Some(o), true) => {
                let name_changed = match &o.name {
                    Some(n) => !self.name.is_empty() && &self.name != n,
                    None => !self.name.is_empty(),
                };
                if self.column_ids != self.origin_ids || name_changed {
                    ChangeState::Modified
                } else {
                    ChangeState::Unchanged
                }
            }
        }
    }
}

#[derive(Debug, Clone)]
pub struct WorkingIndex {
    pub id: ObjId,
    pub name: String,
    pub column_ids: Vec<ObjId>,
    pub unique: bool,
    pub origin: Option<IndexInfo>,
    pub origin_ids: Vec<ObjId>,
    pub dropped: bool,
}

impl WorkingIndex {
    pub fn state(&self) -> ChangeState {
        if self.dropped {
            return ChangeState::Dropped;
        }
        match &self.origin {
            None => ChangeState::Added,
            Some(o) => {
                if self.name != o.name || self.unique != o.unique || self.column_ids != self.origin_ids {
                    ChangeState::Modified
                } else {
                    ChangeState::Unchanged
                }
            }
        }
    }
}

#[derive(Debug, Clone)]
pub struct WorkingFk {
    pub id: ObjId,
    pub name: String,
    pub column_ids: Vec<ObjId>,
    pub ref_schema: String,
    pub ref_table: String,
    /// Comma-separated referenced column list (kept as text for easy editing).
    pub ref_columns: String,
    pub on_delete: String,
    pub on_update: String,
    pub origin: Option<FkInfo>,
    pub origin_ids: Vec<ObjId>,
    pub dropped: bool,
}

impl WorkingFk {
    pub fn state(&self) -> ChangeState {
        if self.dropped {
            return ChangeState::Dropped;
        }
        match &self.origin {
            None => ChangeState::Added,
            Some(o) => {
                let ref_cols_orig = o.ref_columns.join(", ");
                if self.name != o.name
                    || self.column_ids != self.origin_ids
                    || self.ref_schema != o.ref_schema
                    || self.ref_table != o.ref_table
                    || split_cols(&self.ref_columns) != split_cols(&ref_cols_orig)
                    || self.on_delete != o.on_delete
                    || self.on_update != o.on_update
                {
                    ChangeState::Modified
                } else {
                    ChangeState::Unchanged
                }
            }
        }
    }
}

#[derive(Debug, Clone)]
pub struct WorkingCheck {
    pub id: ObjId,
    pub name: String,
    pub expression: String,
    pub origin: Option<CheckInfo>,
    pub dropped: bool,
}

impl WorkingCheck {
    pub fn state(&self) -> ChangeState {
        if self.dropped {
            return ChangeState::Dropped;
        }
        match &self.origin {
            None => ChangeState::Added,
            Some(o) => {
                if self.name != o.name || self.expression != o.expression {
                    ChangeState::Modified
                } else {
                    ChangeState::Unchanged
                }
            }
        }
    }
}

#[derive(Debug, Clone)]
pub struct WorkingTable {
    pub kind: DbKind,
    pub schema: String,
    pub name: String,
    /// `None` = brand-new table (CREATE), `Some` = existing table (ALTER).
    pub original_name: Option<String>,
    pub columns: Vec<WorkingColumn>,
    pub pk: PkState,
    pub foreign_keys: Vec<WorkingFk>,
    pub indexes: Vec<WorkingIndex>,
    pub checks: Vec<WorkingCheck>,
    next_id: ObjId,
}

impl WorkingTable {
    pub fn new_table(kind: DbKind, schema: String) -> Self {
        let mut wt = Self {
            kind,
            schema,
            name: "new_table".to_string(),
            original_name: None,
            columns: Vec::new(),
            pk: PkState::default(),
            foreign_keys: Vec::new(),
            indexes: Vec::new(),
            checks: Vec::new(),
            next_id: 1,
        };
        wt.add_column();
        wt
    }

    pub fn from_structure(kind: DbKind, ts: &TableStructure) -> Self {
        let mut next_id: ObjId = 1;
        let mut alloc = || {
            let id = next_id;
            next_id += 1;
            id
        };

        let columns: Vec<WorkingColumn> = ts
            .columns
            .iter()
            .map(|c| WorkingColumn {
                id: alloc(),
                name: c.name.clone(),
                type_name: c.type_name.clone(),
                not_null: c.not_null,
                default: c.default.clone().unwrap_or_default(),
                identity: c.identity,
                generated: c.generated,
                origin: Some(c.clone()),
                dropped: false,
            })
            .collect();

        let id_of = |name: &str| -> Option<ObjId> {
            columns.iter().find(|c| c.name == name).map(|c| c.id)
        };

        let pk = match &ts.primary_key {
            Some(k) => {
                let ids: Vec<ObjId> = k.columns.iter().filter_map(|c| id_of(c)).collect();
                PkState {
                    present: true,
                    name: k.name.clone().unwrap_or_default(),
                    column_ids: ids.clone(),
                    origin: Some(k.clone()),
                    origin_ids: ids,
                }
            }
            None => PkState::default(),
        };

        let indexes: Vec<WorkingIndex> = ts
            .indexes
            .iter()
            .map(|ix| {
                let ids: Vec<ObjId> = ix.columns.iter().filter_map(|c| id_of(c)).collect();
                WorkingIndex {
                    id: alloc(),
                    name: ix.name.clone(),
                    column_ids: ids.clone(),
                    unique: ix.unique,
                    origin: Some(ix.clone()),
                    origin_ids: ids,
                    dropped: false,
                }
            })
            .collect();

        let foreign_keys: Vec<WorkingFk> = ts
            .foreign_keys
            .iter()
            .map(|fk| {
                let ids: Vec<ObjId> = fk.columns.iter().filter_map(|c| id_of(c)).collect();
                WorkingFk {
                    id: alloc(),
                    name: fk.name.clone(),
                    column_ids: ids.clone(),
                    ref_schema: fk.ref_schema.clone(),
                    ref_table: fk.ref_table.clone(),
                    ref_columns: fk.ref_columns.join(", "),
                    on_delete: fk.on_delete.clone(),
                    on_update: fk.on_update.clone(),
                    origin: Some(fk.clone()),
                    origin_ids: ids,
                    dropped: false,
                }
            })
            .collect();

        let checks: Vec<WorkingCheck> = ts
            .checks
            .iter()
            .map(|ck| WorkingCheck {
                id: alloc(),
                name: ck.name.clone(),
                expression: ck.expression.clone(),
                origin: Some(ck.clone()),
                dropped: false,
            })
            .collect();

        Self {
            kind,
            schema: ts.schema.clone(),
            name: ts.name.clone(),
            original_name: Some(ts.name.clone()),
            columns,
            pk,
            foreign_keys,
            indexes,
            checks,
            next_id,
        }
    }

    fn alloc_id(&mut self) -> ObjId {
        let id = self.next_id;
        self.next_id += 1;
        id
    }

    pub fn add_column(&mut self) -> ObjId {
        let id = self.alloc_id();
        let n = self.columns.iter().filter(|c| c.origin.is_none()).count() + 1;
        self.columns.push(WorkingColumn {
            id,
            name: format!("column_{n}"),
            type_name: default_type(self.kind).to_string(),
            not_null: false,
            default: String::new(),
            identity: IdentityKind::None,
            generated: false,
            origin: None,
            dropped: false,
        });
        id
    }

    pub fn add_index(&mut self) -> ObjId {
        let id = self.alloc_id();
        let n = self.indexes.iter().filter(|i| i.origin.is_none()).count() + 1;
        self.indexes.push(WorkingIndex {
            id,
            name: format!("{}_idx_{n}", self.name),
            column_ids: Vec::new(),
            unique: false,
            origin: None,
            origin_ids: Vec::new(),
            dropped: false,
        });
        id
    }

    pub fn add_fk(&mut self) -> ObjId {
        let id = self.alloc_id();
        let n = self.foreign_keys.iter().filter(|f| f.origin.is_none()).count() + 1;
        self.foreign_keys.push(WorkingFk {
            id,
            name: format!("{}_fk_{n}", self.name),
            column_ids: Vec::new(),
            ref_schema: self.schema.clone(),
            ref_table: String::new(),
            ref_columns: String::new(),
            on_delete: "NO ACTION".to_string(),
            on_update: "NO ACTION".to_string(),
            origin: None,
            origin_ids: Vec::new(),
            dropped: false,
        });
        id
    }

    pub fn add_check(&mut self) -> ObjId {
        let id = self.alloc_id();
        let n = self.checks.iter().filter(|c| c.origin.is_none()).count() + 1;
        self.checks.push(WorkingCheck {
            id,
            name: format!("{}_check_{n}", self.name),
            expression: String::new(),
            origin: None,
            dropped: false,
        });
        id
    }

    pub fn col(&self, id: ObjId) -> Option<&WorkingColumn> {
        self.columns.iter().find(|c| c.id == id)
    }

    pub fn col_name(&self, id: ObjId) -> Option<&str> {
        self.col(id).map(|c| c.name.as_str())
    }

    pub fn is_pk_member(&self, id: ObjId) -> bool {
        self.pk.present && self.pk.column_ids.contains(&id)
    }

    pub fn table_renamed(&self) -> bool {
        matches!(&self.original_name, Some(o) if o != &self.name)
    }

    pub fn change_count(&self) -> usize {
        let mut n = 0;
        n += self
            .columns
            .iter()
            .filter(|c| c.state() != ChangeState::Unchanged)
            .count();
        if self.pk.state() != ChangeState::Unchanged {
            n += 1;
        }
        n += self
            .indexes
            .iter()
            .filter(|i| i.state() != ChangeState::Unchanged)
            .count();
        n += self
            .foreign_keys
            .iter()
            .filter(|f| f.state() != ChangeState::Unchanged)
            .count();
        n += self
            .checks
            .iter()
            .filter(|c| c.state() != ChangeState::Unchanged)
            .count();
        if self.table_renamed() {
            n += 1;
        }
        n
    }

    pub fn has_changes(&self) -> bool {
        self.original_name.is_none() || self.change_count() > 0
    }
}

fn default_type(kind: DbKind) -> &'static str {
    match kind {
        DbKind::Postgres => "text",
        DbKind::MySql => "varchar(255)",
        DbKind::MsSql => "nvarchar(255)",
        DbKind::Sqlite => "TEXT",
    }
}

fn norm(s: &str) -> Option<&str> {
    let t = s.trim();
    if t.is_empty() { None } else { Some(t) }
}

fn norm_opt(s: &Option<String>) -> Option<&str> {
    s.as_deref().and_then(|s| norm(s))
}

pub fn split_cols(s: &str) -> Vec<String> {
    s.split(',')
        .map(|c| c.trim().to_string())
        .filter(|c| !c.is_empty())
        .collect()
}

